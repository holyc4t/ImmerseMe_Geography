test("listed zone", function()
	local land = ns.GetLand("Elwynn Forest", "", false)
	eq(land.terrain, "forest")
	eq(land.listed, true)
	eq(land.zone, "Elwynn Forest")
	eq(land.instance, false)
	ok(type(land.flavor) == "string" and land.flavor ~= "", "flavor")
end)

test("subzone overrides", function()
	local zone = ns.GetLand("Elwynn Forest", "", false)
	local mine = ns.GetLand("Elwynn Forest", "Fargodeep Mine", false)
	eq(mine.terrain, "underground")
	eq(mine.wild, zone.wild)
	eq(mine.subzone, "Fargodeep Mine")
end)

test("instance", function()
	local land = ns.GetLand("The Deadmines", "", true)
	eq(land.terrain, "underground")
	eq(land.ground, nil)
	eq(land.water, nil)
	eq(land.wild, nil)
	eq(land.instance, true)
end)

test("unknown zone", function()
	for _, z in ipairs({ false, "" }) do
		local land = ns.GetLand(z or nil, z or nil, false)
		eq(land.terrain, "grassland")
		eq(land.ground, "soil")
		eq(land.water, "none")
		eq(land.wild, "wild")
		eq(land.zone, "Unknown")
		eq(land.listed, false)
	end
end)

test("truth lookup", function()
	eq(ns.TruthFor("Westfall", "Jangolode Mine").silver, ns.SubZones["Jangolode Mine"].res.silver)
	eq(ns.TruthFor("Westfall", "Sentinel Hill"), ns.Zones["Westfall"].res)
	ok(ns.TruthFor("Westfall", "") ~= ns.Zones["Westfall"].res, "returns a copy, never the data table")
	eq(ns.TruthFor("Nowhere", ""), {})
	local _, entry = ns.TruthFor("Westfall", "")
	eq(entry, ns.Zones["Westfall"])
end)

test("subzone list overlays the zone's", function()
	-- inside the mine, the mine's ores win; Elwynn's herbs, hides and fish still hold
	local res = ns.TruthFor("Elwynn Forest", "Fargodeep Mine")
	eq(res.copper, ns.SubZones["Fargodeep Mine"].res.copper)
	eq(res.tin, ns.SubZones["Fargodeep Mine"].res.tin)
	eq(res.peacebloom, ns.Zones["Elwynn Forest"].res.peacebloom)
	eq(res.lightleather, ns.Zones["Elwynn Forest"].res.lightleather)
end)

test("a zone wears its own colours", function()
	local westfall = ns.GetLand("Westfall", "", false)
	eq(westfall.terrain, "grassland")
	eq(westfall.tone, "gold")
	eq(ns.FacetIcon(westfall, "terrain"), ns.MEDIA .. "land_terrain_grassland_gold")
	eq(ns.FacetIcon(westfall, "ground"), ns.Facets.ground.soil.icon, "only the terrain is toned")

	local mulgore = ns.GetLand("Mulgore", "", false)
	eq(mulgore.terrain, "grassland")
	eq(mulgore.tone, nil, "green needs no tone")
	eq(ns.FacetIcon(mulgore, "terrain"), ns.Facets.terrain.grassland.icon)
end)

test("a zone's colours stay with its own terrain", function()
	local mine = ns.GetLand("Westfall", "Jangolode Mine", false)
	eq(mine.terrain, "underground")
	eq(mine.tone, nil, "a mine in Westfall is not gold")
	eq(ns.FacetIcon(mine, "terrain"), ns.Facets.terrain.underground.icon)

	local town = ns.GetLand("Westfall", "Sentinel Hill", false)
	eq(town.tone, "gold", "an unlisted sub-zone keeps the zone's colours")

	local dungeon = ns.GetLand("Westfall", "", true)
	eq(dungeon.tone, nil, "nor is a dungeon")
	eq(ns.FacetIcon(dungeon, "terrain"), ns.Facets.terrain.underground.icon)
	eq(ns.FacetIcon(dungeon, "water"), nil, "no icon for a facet the land lacks")
end)

test("a tone its terrain doesn't have is ignored", function()
	ns.Zones["Test Vale"] = { terrain = "jungle", tone = "gold" }
	local land = ns.GetLand("Test Vale", "", false)
	ns.Zones["Test Vale"] = nil
	eq(land.tone, nil)
	eq(ns.FacetIcon(land, "terrain"), ns.Facets.terrain.jungle.icon)
end)
